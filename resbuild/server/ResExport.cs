using System.Text;

namespace Resbuild.Server;

public sealed record ExportFile(string Name, string Content);

/// <summary>
/// Builds res.h and res.c, the C every asset is exported as. res.h declares everything (and
/// includes misc.h for <c>byte</c>), res.c defines it; each asset type has a section in both.
/// </summary>
public static class ResExport
{
    public const string HeaderName = "res.h";
    public const string SourceName = "res.c";
    public const string Guard = "__RES_H";

    /// <summary>The names res.h always declares for wavetext_font, which no image may take.</summary>
    public static readonly string[] FontSymbols =
    [
        "wavetext_font_text", "wavetext_font_bitmaps", "WAVETEXT_FONT_TEXT_LENGTH", "WAVETEXT_FONT_BITMAP_COUNT", "WAVETEXT_FONT_BITMAP_BYTES",
    ];

    private const string Banner = "Generated by resbuild - edits here are overwritten.";
    private const int TextBytesPerLine = 16;

    public static IReadOnlyList<ExportFile> Build(FontData font, IReadOnlyList<ImageData> images)
    {
        var h = new StringBuilder();
        var c = new StringBuilder();
        h.Append($"/* {Banner} */\n#ifndef {Guard}\n#define {Guard}\n\n#include \"misc.h\"\n");
        c.Append($"/* {Banner} */\n#include \"{HeaderName}\"\n");

        Section(h, c, "wavetext_font");
        Font(font, h, c);
        Section(h, c, "evlores images");
        Images(images, h, c);

        h.Append("\n#endif\n");
        return [new ExportFile(HeaderName, h.ToString()), new ExportFile(SourceName, c.ToString())];
    }

    /// <summary>
    /// <c>wavetext_font_text</c> is the text, one byte per character: the index of the character's
    /// bitmap. <c>wavetext_font_bitmaps</c> has a bitmap for each character the text uses (and no
    /// others), in character code order.
    /// </summary>
    private static void Font(FontData font, StringBuilder h, StringBuilder c)
    {
        var text = font.Text;
        var codes = text.Select(character => (int)character).Distinct().Order().ToList();
        var index = new Dictionary<int, int>();
        for (var i = 0; i < codes.Count; i++) index[codes[i]] = i;
        var undrawn = codes.Where(code => code != ' ' && !font.Tiles.ContainsKey(code)).ToList();
        var blankRows = WavetextFont.BitmapBytes - WavetextFont.TileHeight;

        h.Append("/* The text, one byte per character: the index of the character's bitmap. */\n");
        h.Append($"#define WAVETEXT_FONT_TEXT_LENGTH {text.Length}\n");
        h.Append("extern const byte wavetext_font_text[];\n\n");
        h.Append("/* A bitmap for each different character in the text, in character code order. Each is\n");
        h.Append($" * {WavetextFont.BitmapBytes} bytes: {WavetextFont.TileHeight} rows of 8 pixels (bit 7 is the leftmost), then {blankRows} blank rows. */\n");
        h.Append($"#define WAVETEXT_FONT_BITMAP_COUNT {codes.Count}\n");
        h.Append($"#define WAVETEXT_FONT_BITMAP_BYTES {WavetextFont.BitmapBytes}\n");
        h.Append("extern const byte wavetext_font_bitmaps[];\n");

        // C has no empty arrays, so an empty text still gets a byte and a bitmap (not counted).
        c.Append("const byte wavetext_font_text[] = {\n");
        if (text.Length == 0) c.Append("    0x00, /* the text is empty: a placeholder */\n");
        for (var start = 0; start < text.Length; start += TextBytesPerLine)
        {
            var chunk = text.Substring(start, Math.Min(TextBytesPerLine, text.Length - start));
            var bytes = string.Concat(chunk.Select(character => Hex(index[character]) + ","));
            c.Append($"    {bytes,-(TextBytesPerLine * 5)} /* {Comment(chunk)} */\n");
        }
        c.Append("};\n\n");

        if (undrawn.Count > 0) c.Append($"/* No tile drawn yet, so blank: {string.Join(" ", undrawn.Select(CharName))} */\n");
        c.Append("const byte wavetext_font_bitmaps[] = {\n");
        if (codes.Count == 0) c.Append($"    {Bytes(new byte[WavetextFont.BitmapBytes])} /* the text is empty: a placeholder */\n");
        foreach (var code in codes)
        {
            var bitmap = new byte[WavetextFont.BitmapBytes];
            if (font.Tiles.TryGetValue(code, out var rows)) rows.CopyTo(bitmap, 0);
            c.Append($"    {Bytes(bitmap)} /* {Hex(index[code])} {CharName(code)} */\n");
        }
        c.Append("};\n");
    }

    /// <summary>
    /// Per image, a byte array under its variable name plus <c>NAME_WIDTH</c> and
    /// <c>NAME_HEIGHT</c> (in pixels). Each byte holds two pixels, one above the other: the bottom
    /// one in the low nibble, the top one in the high nibble, the way evlores.c fills a
    /// character cell's colour byte. So each row of bytes covers two rows of pixels, and an image
    /// can be copied straight into colour RAM. A row of bytes per line of res.c, so the hex
    /// digits show the picture (top row, then bottom row, in each byte).
    /// </summary>
    private static void Images(IReadOnlyList<ImageData> images, StringBuilder h, StringBuilder c)
    {
        h.Append("/* Two pixels per byte, one above the other: the low nibble is the bottom pixel, the high\n");
        h.Append(" * nibble the top one, each a microbee palette colour (0-15). Each row of bytes is two rows\n");
        h.Append(" * of pixels: pixels (x, 2r) and (x, 2r + 1) are name[r * NAME_WIDTH + x], and an image is\n");
        h.Append(" * NAME_WIDTH * NAME_HEIGHT / 2 bytes. Pixels are twice as high as wide. */\n");
        if (images.Count == 0)
        {
            h.Append("/* No images yet. */\n");
            c.Append("/* No images yet. */\n");
            return;
        }

        for (var i = 0; i < images.Count; i++)
        {
            var image = images[i];
            var upper = image.Name.ToUpperInvariant();
            h.Append($"\n/* {image.Name}: {image.Width} x {image.Height} */\n");
            h.Append($"#define {upper}_WIDTH {image.Width}\n");
            h.Append($"#define {upper}_HEIGHT {image.Height}\n");
            h.Append($"extern const byte {image.Name}[];\n");

            if (i > 0) c.Append('\n');
            c.Append($"/* {image.Name}: {image.Width} x {image.Height} */\n");
            c.Append($"const byte {image.Name}[] = {{\n");
            for (var y = 0; y < image.Height; y += 2)
            {
                c.Append("    ");
                for (var x = 0; x < image.Width; x++)
                {
                    var top = image.Pixels[y * image.Width + x] & 0xf;
                    var bottom = image.Pixels[(y + 1) * image.Width + x] & 0xf;
                    c.Append(Hex((top << 4) | bottom)).Append(',');
                }
                c.Append('\n');
            }
            c.Append("};\n");
        }
    }

    private static void Section(StringBuilder h, StringBuilder c, string title)
    {
        var rule = $"\n/* ---- {title} {new string('-', Math.Max(4, 80 - 12 - title.Length))} */\n\n";
        h.Append(rule);
        c.Append(rule);
    }

    private static string Hex(int value) => $"0x{value:x2}";

    private static string Bytes(byte[] values) => string.Concat(values.Select(value => Hex(value) + ","));

    /// <summary>Text that is safe inside a <c>/* */</c> comment.</summary>
    private static string Comment(string text) => text.Replace("*/", "*\\/").Replace("/*", "/\\*");

    private static string CharName(int code) => code == ' ' ? "space" : $"'{Comment(((char)code).ToString())}'";
}
